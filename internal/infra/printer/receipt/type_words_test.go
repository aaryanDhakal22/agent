// The type line's words (icons.go) are drawn once in Go Bold at 46 px (the
// owner's pick 2026-11-14, the sample tool's typefaceLine) and kept as dot
// rows in type_words.go: the terminal (lib/platform/printer/icons.dart) and
// the fake printer (deploy/fakeprinter ICONS) carry the same rows byte for
// byte. This test draws them again and fails when type_words.go differs;
// -update rewrites it (then copy the rows to the other two).

// renderTypeWord draws word with its pen at x 0 on the 42-dot baseline of a
// typeRows-tall line: the dots that came out black, typeArt.w dots wide (the
// word's advance).
func renderTypeWord(t *testing.T, word string) typeArt {
	t.Helper()
	ft, err := opentype.Parse(gobold.TTF)
	if err != nil {
		t.Fatal(err)
	}
	fc, err := opentype.NewFace(ft, &opentype.FaceOptions{Size: typeWordPx, DPI: 72, Hinting: font.HintingFull})
	if err != nil {
		t.Fatal(err)
	}
	defer fc.Close()
	w := font.MeasureString(fc, word).Ceil()
	const pad = 32
	img := image.NewGray(image.Rect(0, 0, w+2*pad, typeRows))
	draw.Draw(img, img.Bounds(), image.White, image.Point{}, draw.Src)
	d := font.Drawer{Dst: img, Src: image.Black, Face: fc, Dot: fixed.P(pad, typeBaseline)}
	d.DrawString(word)
	wb := (w + 7) / 8
	var rows []string
	for y := 0; y < typeRows; y++ {
		row := make([]byte, wb)
		for x := 0; x < w+2*pad; x++ {
			if img.GrayAt(x, y).Y >= 128 {
				continue
			}
			if x < pad || x >= pad+w {
				t.Fatalf("%s: ink outside its advance at x %d", word, x-pad)
			}
			row[(x-pad)/8] |= 0x80 >> ((x - pad) % 8)
		}
		rows = append(rows, fmt.Sprintf("%x", row))
	}
	return typeArt{w: w, rows: rows}
}

func TestTypeWordArt(t *testing.T) {
	words := []string{"PICKUP", "COUNTER", "DELIVERY"}
	got := map[string]typeArt{}
	for _, w := range words {
		got[w] = renderTypeWord(t, w)
	}
	if *update {
		var b strings.Builder
		b.WriteString("// Code generated by TestTypeWordArt (go test -run TestTypeWordArt -update); DO NOT EDIT.\n\npackage receipt\n\n")
		b.WriteString("// typeWords: each order type's word in Go Bold at 46 px, its pen at x 0 on the 42-dot baseline of a\n")
		b.WriteString("// 52-dot line: w dots wide (the word's advance), a row of hex per dot row (MSB = the leftmost dot).\n")
		b.WriteString("// Byte-identical in the terminal's icons.dart (kTypeWords) and the fake printer (TYPE_WORDS).\n")
		b.WriteString("var typeWords = map[string]typeArt{\n")
		keys := append([]string(nil), words...)
		sort.Strings(keys)
		for _, k := range keys {
			fmt.Fprintf(&b, "\t%q: {w: %d, rows: []string{\n", k, got[k].w)
			for _, r := range got[k].rows {
				fmt.Fprintf(&b, "\t\t%q,\n", r)
			}
			b.WriteString("\t}},\n")
		}
		b.WriteString("}\n")
		if err := os.WriteFile("type_words.go", []byte(b.String()), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	for _, w := range words {
		have, ok := typeWords[w]
		if !ok || have.w != got[w].w || strings.Join(have.rows, ",") != strings.Join(got[w].rows, ",") {
			t.Errorf("%s: type_words.go differs from Go Bold at %d px (go test -run TestTypeWordArt -update)", w, typeWordPx)
		}
	}
}
